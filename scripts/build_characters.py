def load_chapters():
    return {p.stem: p.read_text(encoding="utf-8") for p in sorted(CH.glob("*.txt"))}


def main():
    try:
        out_arg, rest = jsio.option(sys.argv[1:], "--output")
    except jsio.JsDataError as e:
        raise SystemExit("✗ %s" % e)
    unknown = [a for a in rest if a.startswith("-")]
    if unknown:
        raise SystemExit("✗ 未知参数：%s（本脚本只做初始化，没有 --force）" % unknown)

    target = pathlib.Path(out_arg) if out_arg else OUT
    try:
        jsio.refuse_existing(
            target,
            "本脚本只做显式初始化（没有 --force）；正式人物志由 merge_minor.py / sync_minor.py 维护。")
    except jsio.JsDataError as e:
        raise SystemExit("✗ %s" % e)

    chs = load_chapters()
    if len(chs) != 361:
        raise SystemExit("✗ 语料章数 %d != 361，请先跑 corpus_extract.py" % len(chs))

    rows, missing = [], []
    for (cid, name, full, aliases, faction, family, born, died,
         title, tier, bio, arc, patterns) in ROSTER:
        rx = [re.compile(p) for p in patterns]
        hits = sorted(k for k, t in chs.items() if any(r.search(t) for r in rx))
        if not hits:
            missing.append(name)
        rows.append({
            "id": cid, "name": name, "full": full, "aliases": aliases,
            "faction": faction, "family": family, "born": born, "died": died,
            "title": title, "tier": tier, "bio": bio, "arc": arc,
            "chapters": hits, "names": {"cao": name}, "flag": None,
        })

    if missing:
        raise SystemExit("✗ 以下人物零命中，正则需修：%s" % missing)

    lines = [
        "// data/characters.js — 人物志（初始化候选）",
        "// ⚠ 骨架（初始化）：仅内置 ROSTER 的 %d 位详录人物；" % len(rows),
        "//   139 位简录与人工修订不在本脚本范围内（由 merge_minor.py / sync_minor.py 维护）。",
        "//   chapters（出场章节索引）由 corpus/ 自动抽取（提示级，需人工校订）。",
        "// 阵营色见 docs/schema.md §8。",
        "const CHARACTERS = [",
    ]
    for r in rows:
        lines.append("  " + jsio.render_character(r) + ",")
    lines += ["];", "", 'if (typeof module !== "undefined") module.exports = { CHARACTERS };', ""]

    text = "\n".join(lines)
    try:
        jsio.assert_const_text(text, "CHARACTERS", {r["id"]: {"id": r["id"]} for r in rows})
    except jsio.JsDataError as e:
        raise SystemExit("✗ 生成结果校验失败，未写入：%s" % e)
    jsio.atomic_write(target, text, create=True)

    print("✓ %d 位人物（骨架）→ %s" % (len(rows), target))
    print("  仅详录人物；简录与人工修订不在本脚本范围（merge_minor.py / sync_minor.py 维护）。")
    for r in rows:
        print("  %-14s%4d 章  %s" % (r["id"], len(r["chapters"]), r["name"]))


if __name__ == "__main__":
    main()
